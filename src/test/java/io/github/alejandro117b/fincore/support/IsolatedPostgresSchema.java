package io.github.alejandro117b.fincore.support;

import java.sql.SQLException;
import java.util.Arrays;
import org.flywaydb.core.Flyway;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.DynamicPropertyRegistry;

/** Test-only schema routing, checked before Flyway can execute any migration. */
public final class IsolatedPostgresSchema {
    private IsolatedPostgresSchema() { }

    public static void register(DynamicPropertyRegistry properties, String schema) {
        requireOwnedName(schema);
        properties.add("spring.flyway.schemas", () -> schema);
        properties.add("spring.flyway.default-schema", () -> schema);
        properties.add("spring.jpa.properties.hibernate.default_schema", () -> schema);
        // No public fallback, including on connections created before the schema exists.
        properties.add("spring.datasource.hikari.connection-init-sql", () -> "SET search_path TO " + schema);
    }

    public static void migrate(Flyway flyway, String schema) {
        requireOwnedName(schema);
        var configuration = flyway.getConfiguration();
        if (!schema.equals(configuration.getDefaultSchema())
                || !Arrays.equals(configuration.getSchemas(), new String[]{schema})) {
            throw new IllegalStateException("Flyway must target only this test's generated schema");
        }
        try (var connection = configuration.getDataSource().getConnection();
             var statement = connection.createStatement();
             var result = statement.executeQuery("SELECT current_setting('search_path')")) {
            if (!result.next() || !schema.equals(result.getString(1))) {
                throw new IllegalStateException("Test connections must exclude public from search_path");
            }
        } catch (SQLException failure) {
            throw new IllegalStateException("Cannot verify PostgreSQL test schema isolation", failure);
        }
        // Keep real Flyway migrations and their validation; Hibernate still validates afterward.
        flyway.migrate();
    }

    public static void drop(JdbcTemplate jdbc, String schema) {
        requireOwnedName(schema);
        jdbc.execute("DROP SCHEMA \"" + schema + "\" CASCADE");
    }

    private static void requireOwnedName(String schema) {
        if (schema == null || !schema.matches("(?:application|persistence)_test_[0-9a-f]{32}")) {
            throw new IllegalArgumentException("Refusing to use a schema not generated by these tests");
        }
    }
}
